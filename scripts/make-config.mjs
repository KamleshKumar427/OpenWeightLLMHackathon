#!/usr/bin/env node
// Turns .env into selkea-extension/config.local.js, the one file the browser extension reads
// its private server details and keys from. A Chrome extension cannot read .env while it runs,
// so this script bridges the two. The output is git-ignored; .env is the only source of truth.
//
//   node scripts/make-config.mjs
//
// No .env, or an empty one, produces an empty config and the extension falls back to the public
// LUMI Aitta endpoint (you paste a token in its Settings panel).

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const envPath = path.join(root, ".env");
const outPath = path.join(root, "selkea-extension", "config.local.js");

function parseEnv(text) {
  const env = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const m = line.match(/^([A-Za-z0-9_]+)\s*=\s*(.*)$/);
    if (!m) continue;
    env[m[1]] = m[2].replace(/\s+#.*$/, "").replace(/^["']|["']$/g, "").trim();
  }
  return env;
}

const env = fs.existsSync(envPath) ? parseEnv(fs.readFileSync(envPath, "utf8")) : {};
const config = { hackathon: null, apiKeys: {} };

if (env.HACKATHON_HOST) {
  config.hackathon = {
    host: env.HACKATHON_HOST,
    h200Port: Number(env.HACKATHON_H200_PORT) || 9002,
    a100Port: Number(env.HACKATHON_A100_PORT) || 9001,
  };
  if (env.HACKATHON_API_KEY) config.apiKeys[env.HACKATHON_HOST] = env.HACKATHON_API_KEY;
}
if (env.AITTA_TOKEN) config.apiKeys["aitta-api.csc.fi"] = env.AITTA_TOKEN;

const banner =
  "// GENERATED by scripts/make-config.mjs from .env. Git-ignored. Do not edit or commit.\n";
fs.writeFileSync(outPath, banner + "var SELKEA_CONFIG = " + JSON.stringify(config, null, 2) + ";\n");

const keys = Object.keys(config.apiKeys).length;
console.log(`Wrote ${path.relative(root, outPath)}`);
console.log(`  hackathon servers: ${config.hackathon ? config.hackathon.host : "not configured"}`);
console.log(`  keys loaded: ${keys}`);
if (!fs.existsSync(envPath)) console.log("  (no .env found; copy .env.example to .env to add your own)");
